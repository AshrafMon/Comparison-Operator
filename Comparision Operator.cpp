#include <iostream>
using namespace std;

//This code for Apply Comparision Operator
    
int main() {
	
// Decleration of variables	
    
	int Num1,Num2; 
	
// Initialization of variables
	
	cout<<"PLZ Enter 1st Number = ";
	cin>>Num1;
	cout<<"PLZ Enter 2nd Number = ";
	cin>>Num2;
	
// equal
   cout<<"Is Num1=Num2 ? "<<(Num1==Num2)<<endl;
  
//Not equal
   cout<<"Is Num1 and Num2 does not equal ? "<<(Num1!=Num2)<<endl;
    
//Greater Than 
    cout<<"Is Num1>Num2 ? "<<(Num1>Num2)<<endl;

//Less Than 
    cout<<"Is Num1<Num2 ? "<<(Num1<Num2)<<endl;

//Greater Than Or equal 
    cout<<"Is Num1>=Num2 ? "<<(Num1>=Num2)<<endl;

//Less Than Or equal
    cout<<"Is Num1<=Num2 ? "<<(Num1<=Num2)<<endl;


    return 0;
}

